function catalog(keys) {
  return Object.fromEntries(keys.map((key) => [key, ""]));
}

function writeJson(file, keys) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(catalog(keys), null, 2)}\n`, "utf8");
}

const groups = [
  ["Documentation", "community_documentation_template.json", documentation],
  ["Mod-Manager", "community_mod_manager_template.json", modManager],
  ["Sandbox-Mod", "community_sandbox_mod_template.json", sandboxMod],
];

for (const [folder, templateName, keys] of groups) {
  writeJson(path.join(root, "translations", templateName), keys);
  for (const language of languages) {
    writeJson(path.join(root, "community-translations", "Additional-Blank-Translations", folder, `${language}.json`), keys);
  }
}

console.log(`Created ${groups.length * languages.length} additional blank translation files.`);
